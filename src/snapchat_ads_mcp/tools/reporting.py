"""Performance stats (synchronous), asynchronous CSV reports, and entity change logs.

Synchronous stats come straight back as JSON and are flattened here into rows.
Snap rejects synchronous requests whose response would be too large (error
E9001): use an async report for wide breakdowns or long HOUR/DAY ranges. Async
reports are generated by Snap in the background, downloaded as CSV and parsed
in memory; rows are never written to disk or the audit log.

Money metrics (spend, *_value) are micro-currency; each row also gets a
`<metric>_amount` column in whole currency units.
"""

from __future__ import annotations

import asyncio
import time
from typing import Any, Literal

from mcp.server.mcpserver import Context

from ..client import SnapchatAdsClient, check_id, unwrap
from ._progress import report, run_blocking

ENTITY_PATHS = {
    "ad_account": "adaccounts",
    "campaign": "campaigns",
    "ad_squad": "adsquads",
    "ad": "ads",
    "creative": "creatives",
    "media": "media",
}
EntityType = Literal["ad_account", "campaign", "ad_squad", "ad", "creative", "media"]
ASYNC_ENTITIES = ("ad_account", "campaign", "ad_squad", "ad")
GRANULARITIES = ("TOTAL", "DAY", "HOUR", "LIFETIME")
DEFAULT_FIELDS = "impressions,swipes,spend"
MONEY_METRICS = {"spend", "coupon_used_local", "coupon_used_usd"}
MAX_STATS_PAGES = 20

GUIDE = """\
granularity: TOTAL (needs day-boundary start/end, or none for lifetime), DAY (range
up to 31 days), HOUR (up to 7 days), LIFETIME (no dates). start_time/end_time are
ISO 8601 and must fall on day boundaries in the ad account's timezone for DAY, e.g.
start_time '2026-11-01T00:00:00', end_time '2026-11-08T00:00:00' for 1-7 November.
fields (comma-separated): impressions, swipes, spend, video_views, video_views_15s,
uniques, frequency, screen_time_millis, view_completion, total_installs,
conversion_purchases, conversion_purchases_value, conversion_add_cart,
conversion_sign_ups, conversion_page_views, landing_page_views, engaged_views ...
breakdown: campaign (ad account only), adsquad (campaign only) or ad.
report_dimension (insights, not with HOUR): country, region, dma, gender, age,
'age,gender', os, 'country,os', make, lifestyle_category.
Attribution: swipe_up_attribution_window 1_DAY/7_DAY/28_DAY (default),
view_attribution_window none/1_HOUR/3_HOUR/6_HOUR/1_DAY (default)/7_DAY;
action_report_time conversion (default) or impression. Metrics finalise about
48 hours after the end of a day."""


def stats_params(
    *,
    granularity: str,
    fields: str,
    start_time: str | None,
    end_time: str | None,
    breakdown: str | None,
    report_dimension: str | None,
    swipe_up_attribution_window: str | None,
    view_attribution_window: str | None,
    action_report_time: str | None,
    conversion_source_types: str | None,
    omit_empty: bool,
    extra_params: dict[str, Any] | None,
) -> dict[str, Any]:
    granularity = granularity.upper()
    if granularity not in GRANULARITIES:
        raise ValueError(f"granularity must be one of {', '.join(GRANULARITIES)}.")
    if granularity in {"DAY", "HOUR"} and not (start_time and end_time):
        raise ValueError(f"{granularity} granularity needs start_time and end_time.")
    if granularity == "LIFETIME" and (start_time or end_time):
        raise ValueError("LIFETIME granularity takes no start_time or end_time.")
    if granularity == "HOUR" and report_dimension:
        raise ValueError("report_dimension (insights) isn't available with HOUR granularity.")
    params: dict[str, Any] = {"granularity": granularity, "fields": fields or DEFAULT_FIELDS}
    optional = {
        "start_time": start_time,
        "end_time": end_time,
        "breakdown": breakdown,
        "report_dimension": report_dimension,
        "swipe_up_attribution_window": swipe_up_attribution_window,
        "view_attribution_window": view_attribution_window,
        "action_report_time": action_report_time,
        "conversion_source_types": conversion_source_types,
    }
    params.update({k: v for k, v in optional.items() if v})
    if omit_empty:
        params["omit_empty"] = "true"
    for key, value in (extra_params or {}).items():
        if key in {"async", "async_format", "report_run_id"}:
            raise ValueError(f"{key} is set by the report tools; don't pass it in extra_params.")
        params[key] = value
    return params


def _with_amounts(row: dict[str, Any]) -> dict[str, Any]:
    extra: dict[str, Any] = {}
    for key, value in row.items():
        if (key in MONEY_METRICS or key.endswith("_value")) and isinstance(value, int | float):
            extra[f"{key}_amount"] = round(value / 1_000_000, 6)
    return {**row, **extra} if extra else row


def _emit(base: dict[str, Any], node: dict[str, Any], rows: list[dict[str, Any]]) -> None:
    dims = node.get("dimension_stats")
    if isinstance(dims, list) and dims:
        for d in dims:
            if isinstance(d, dict):
                rows.append(_with_amounts({**base, **d}))
        return
    stats = node.get("stats")
    rows.append(_with_amounts({**base, **(stats if isinstance(stats, dict) else {})}))


def _walk(node: dict[str, Any], parent: dict[str, Any], rows: list[dict[str, Any]]) -> None:
    base = {
        **parent,
        "id": node.get("id", parent.get("id")),
        "type": node.get("type", parent.get("type")),
        "granularity": node.get("granularity", parent.get("granularity")),
    }
    breakdown = node.get("breakdown_stats")
    if isinstance(breakdown, dict) and breakdown:
        for level, children in breakdown.items():
            for child in children or []:
                if isinstance(child, dict):
                    _walk(child, {**base, "breakdown": level, "parent_id": base["id"]}, rows)
        return
    series = node.get("timeseries")
    if isinstance(series, list):
        for point in series:
            if isinstance(point, dict):
                _emit(
                    {
                        **base,
                        "start_time": point.get("start_time"),
                        "end_time": point.get("end_time"),
                    },
                    point,
                    rows,
                )
        return
    _emit(
        {**base, "start_time": node.get("start_time"), "end_time": node.get("end_time")}, node, rows
    )


def flatten_stats(payload: Any) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Turn a stats response into flat rows plus finalisation metadata."""
    rows: list[dict[str, Any]] = []
    meta: dict[str, Any] = {}
    for stat in unwrap(payload):
        for key in (
            "finalized_data_end_time",
            "conversion_data_processed_end_time",
            "swipe_up_attribution_window",
            "view_attribution_window",
        ):
            if key in stat:
                meta[key] = stat[key]
        _walk(stat, {}, rows)
    return rows, meta


def _scrub_changelog(entry: dict[str, Any]) -> dict[str, Any]:
    # Keep who changed what by user_id, but not their email address.
    return {k: v for k, v in entry.items() if k not in {"email"}}


def register(mcp, client: SnapchatAdsClient) -> None:
    def entity_path(entity_type: str, entity_id: str | None) -> str:
        if entity_type not in ENTITY_PATHS:
            raise ValueError(f"entity_type must be one of {', '.join(ENTITY_PATHS)}.")
        if entity_type == "ad_account":
            eid = client.resolve_ad_account(entity_id)
        else:
            if not entity_id:
                raise ValueError(f"Pass entity_id: the {entity_type.replace('_', ' ')} ID.")
            eid = check_id(entity_id, "entity_id")
        return f"/v1/{ENTITY_PATHS[entity_type]}/{eid}"

    def create_async(path: str, params: dict[str, Any]) -> dict[str, Any]:
        out = client.request(
            "GET", f"{path}/stats", params={**params, "async": "true", "async_format": "csv"}
        )
        found = unwrap(out, "async_stats_reports")
        if not found or not found[0].get("report_run_id"):
            raise RuntimeError(f"Snap returned no report_run_id: {out}")
        return found[0]

    def get_async(path: str, report_run_id: str) -> dict[str, Any]:
        if not report_run_id or "/" in report_run_id or len(report_run_id) > 300:
            raise ValueError("report_run_id looks wrong; pass the value from create_async_report.")
        out = client.request("GET", f"{path}/stats_report", params={"report_run_id": report_run_id})
        found = unwrap(out, "async_stats_reports")
        if not found:
            raise RuntimeError(f"No report status in the response: {out}")
        return found[0]

    def rows_payload(status: dict[str, Any], max_rows: int) -> dict[str, Any]:
        rows = client.download_report(str(status["result"]))
        return {
            "report_run_id": status.get("report_run_id"),
            "status": status.get("async_status"),
            "row_count": len(rows),
            "rows": rows[: max(0, max_rows)],
            "truncated": len(rows) > max_rows,
        }

    @mcp.tool(
        description=(
            "Get performance stats for an ad account, campaign, ad squad, ad, creative or "
            "media, returned as flat rows (one per entity, day/hour and dimension value). "
            "entity_id defaults to the default ad account for entity_type 'ad_account'. "
            "Creatives and media support only DAY and LIFETIME. For large pulls use "
            "snapchat_ads_run_report instead (Snap rejects oversized synchronous requests).\n\n"
            + GUIDE
        )
    )
    async def snapchat_ads_get_stats(
        entity_type: EntityType = "ad_account",
        entity_id: str | None = None,
        granularity: Literal["TOTAL", "DAY", "HOUR", "LIFETIME"] = "TOTAL",
        fields: str = DEFAULT_FIELDS,
        start_time: str | None = None,
        end_time: str | None = None,
        breakdown: Literal["campaign", "adsquad", "ad"] | None = None,
        report_dimension: str | None = None,
        swipe_up_attribution_window: Literal["1_DAY", "7_DAY", "28_DAY"] | None = None,
        view_attribution_window: Literal["none", "1_HOUR", "3_HOUR", "6_HOUR", "1_DAY", "7_DAY"]
        | None = None,
        action_report_time: Literal["conversion", "impression"] | None = None,
        conversion_source_types: str | None = None,
        omit_empty: bool = False,
        extra_params: dict[str, Any] | None = None,
        max_rows: int = 2000,
    ) -> dict[str, Any]:
        path = entity_path(entity_type, entity_id)
        if entity_type in {"creative", "media"} and granularity.upper() not in {"DAY", "LIFETIME"}:
            raise ValueError("Creative and media stats support only DAY and LIFETIME granularity.")
        params = stats_params(
            granularity=granularity,
            fields=fields,
            start_time=start_time,
            end_time=end_time,
            breakdown=breakdown,
            report_dimension=report_dimension,
            swipe_up_attribution_window=swipe_up_attribution_window,
            view_attribution_window=view_attribution_window,
            action_report_time=action_report_time,
            conversion_source_types=conversion_source_types,
            omit_empty=omit_empty,
            extra_params=extra_params,
        )
        if breakdown:
            params["limit"] = 200
        rows: list[dict[str, Any]] = []
        meta: dict[str, Any] = {}
        next_path: str | None = f"{path}/stats"
        query: dict[str, Any] = params
        pages = 0
        while next_path and pages < MAX_STATS_PAGES and len(rows) < max_rows:
            out = await run_blocking(client.request, "GET", next_path, params=query)
            page_rows, page_meta = flatten_stats(out)
            rows.extend(page_rows)
            meta.update(page_meta)
            pages += 1
            link = (out.get("paging") or {}).get("next_link") if isinstance(out, dict) else None
            next_path, query = client.next_page(link)
        return {
            "rows": rows[: max(0, max_rows)],
            "row_count": len(rows),
            "truncated": len(rows) > max_rows or bool(next_path),
            "params": params,
            **meta,
        }

    async_desc = (
        "Asynchronous reports cover ad accounts, campaigns, ad squads and ads, have no "
        "synchronous size limit or HOUR 7-day cap, and are kept by Snap for 7 days. "
        "Same parameters as snapchat_ads_get_stats.\n\n" + GUIDE
    )

    @mcp.tool(
        description=(
            "Start an asynchronous CSV report. Poll snapchat_ads_get_async_report, then call "
            "snapchat_ads_download_async_report (or use snapchat_ads_run_report for all three). "
            + async_desc
        )
    )
    def snapchat_ads_create_async_report(
        entity_type: Literal["ad_account", "campaign", "ad_squad", "ad"] = "ad_account",
        entity_id: str | None = None,
        granularity: Literal["TOTAL", "DAY", "HOUR", "LIFETIME"] = "DAY",
        fields: str = DEFAULT_FIELDS,
        start_time: str | None = None,
        end_time: str | None = None,
        breakdown: Literal["campaign", "adsquad", "ad"] | None = None,
        report_dimension: str | None = None,
        swipe_up_attribution_window: Literal["1_DAY", "7_DAY", "28_DAY"] | None = None,
        view_attribution_window: Literal["none", "1_HOUR", "3_HOUR", "6_HOUR", "1_DAY", "7_DAY"]
        | None = None,
        action_report_time: Literal["conversion", "impression"] | None = None,
        conversion_source_types: str | None = None,
        omit_empty: bool = True,
        extra_params: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        path = entity_path(entity_type, entity_id)
        params = stats_params(
            granularity=granularity,
            fields=fields,
            start_time=start_time,
            end_time=end_time,
            breakdown=breakdown,
            report_dimension=report_dimension,
            swipe_up_attribution_window=swipe_up_attribution_window,
            view_attribution_window=view_attribution_window,
            action_report_time=action_report_time,
            conversion_source_types=conversion_source_types,
            omit_empty=omit_empty,
            extra_params=extra_params,
        )
        started = create_async(path, params)
        return {
            "report_run_id": started.get("report_run_id"),
            "status": started.get("async_status"),
            "entity_type": entity_type,
            "entity_id": path.rsplit("/", 1)[-1],
        }

    @mcp.tool()
    def snapchat_ads_get_async_report(
        report_run_id: str,
        entity_type: Literal["ad_account", "campaign", "ad_squad", "ad"] = "ad_account",
        entity_id: str | None = None,
    ) -> dict[str, Any]:
        """Check an async report: STARTED, RUNNING, COMPLETED or FAILED.

        Pass the same entity_type and entity_id used to create it. When COMPLETED,
        call snapchat_ads_download_async_report.
        """
        status = get_async(entity_path(entity_type, entity_id), report_run_id)
        return {
            "report_run_id": status.get("report_run_id"),
            "status": status.get("async_status"),
            "ready": bool(status.get("result")) and status.get("async_status") == "COMPLETED",
        }

    @mcp.tool()
    async def snapchat_ads_download_async_report(
        report_run_id: str,
        entity_type: Literal["ad_account", "campaign", "ad_squad", "ad"] = "ad_account",
        entity_id: str | None = None,
        max_rows: int = 2000,
    ) -> dict[str, Any]:
        """Download a COMPLETED async report and return its rows (up to max_rows).

        Rows are parsed in memory only; row_count is the full count. Files over
        SNAPCHAT_ADS_MAX_DOWNLOAD_MB are refused.
        """
        path = entity_path(entity_type, entity_id)
        status = await run_blocking(get_async, path, report_run_id)
        if status.get("async_status") != "COMPLETED" or not status.get("result"):
            return {
                "report_run_id": report_run_id,
                "status": status.get("async_status"),
                "message": "Report isn't ready; check again with snapchat_ads_get_async_report.",
            }
        return await run_blocking(rows_payload, status, max_rows)

    @mcp.tool(
        description=(
            "Run an async report end to end: start it, wait with progress updates, download "
            "the CSV and return its rows. Adds timeout_seconds (default 600), poll_seconds "
            "(default 10) and max_rows (default 2000). If it times out, the report_run_id is "
            "returned so you can check later. " + async_desc
        )
    )
    async def snapchat_ads_run_report(
        entity_type: Literal["ad_account", "campaign", "ad_squad", "ad"] = "ad_account",
        entity_id: str | None = None,
        granularity: Literal["TOTAL", "DAY", "HOUR", "LIFETIME"] = "DAY",
        fields: str = DEFAULT_FIELDS,
        start_time: str | None = None,
        end_time: str | None = None,
        breakdown: Literal["campaign", "adsquad", "ad"] | None = None,
        report_dimension: str | None = None,
        swipe_up_attribution_window: Literal["1_DAY", "7_DAY", "28_DAY"] | None = None,
        view_attribution_window: Literal["none", "1_HOUR", "3_HOUR", "6_HOUR", "1_DAY", "7_DAY"]
        | None = None,
        action_report_time: Literal["conversion", "impression"] | None = None,
        conversion_source_types: str | None = None,
        omit_empty: bool = True,
        extra_params: dict[str, Any] | None = None,
        max_rows: int = 2000,
        timeout_seconds: float = 600,
        poll_seconds: float = 10,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        path = entity_path(entity_type, entity_id)
        params = stats_params(
            granularity=granularity,
            fields=fields,
            start_time=start_time,
            end_time=end_time,
            breakdown=breakdown,
            report_dimension=report_dimension,
            swipe_up_attribution_window=swipe_up_attribution_window,
            view_attribution_window=view_attribution_window,
            action_report_time=action_report_time,
            conversion_source_types=conversion_source_types,
            omit_empty=omit_empty,
            extra_params=extra_params,
        )
        started = await run_blocking(create_async, path, params)
        run_id = str(started["report_run_id"])
        step = 1
        await report(ctx, step, None, "Requested report")
        deadline = time.monotonic() + timeout_seconds
        while True:
            status = await run_blocking(get_async, path, run_id)
            state = status.get("async_status")
            step += 1
            if state == "COMPLETED" and status.get("result"):
                await report(ctx, step, None, "Report ready; downloading")
                payload = await run_blocking(rows_payload, status, max_rows)
                await report(ctx, step + 1, None, f"Downloaded {payload['row_count']} rows")
                return payload
            if state in {"FAILED", "CANCELLED", "ERROR"}:
                return {"report_run_id": run_id, "status": state}
            if time.monotonic() >= deadline:
                return {
                    "report_run_id": run_id,
                    "status": state,
                    "entity_type": entity_type,
                    "entity_id": path.rsplit("/", 1)[-1],
                    "message": "Still generating. Check later with snapchat_ads_get_async_report.",
                }
            await report(ctx, step, None, f"Report {state}; waiting")
            await asyncio.sleep(max(0.0, poll_seconds))

    @mcp.tool()
    async def snapchat_ads_get_change_log(
        entity_type: Literal["campaign", "ad_squad", "ad", "creative"],
        entity_id: str,
        max_results: int = 100,
    ) -> dict[str, Any]:
        """Show Snap's change history for a campaign, ad squad, ad or creative.

        Covers changes made anywhere (Ads Manager, other tools, this server),
        newest first. Editors are shown by user_id; email addresses are dropped.
        """
        eid = check_id(entity_id, "entity_id")
        items, truncated = await run_blocking(
            client.paginate,
            f"/v1/{ENTITY_PATHS[entity_type]}/{eid}/external_changelogs",
            None,
            key="changelogs",
            max_results=max_results,
        )
        return {
            "changelogs": [_scrub_changelog(i) for i in items],
            "count": len(items),
            "truncated": truncated,
        }
